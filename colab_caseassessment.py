# --- Lecture 14: PCA ---
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
pca_vars = ['teaching','research','citations','international','income','ratio_cap','international_students','female_pct']
P = df[pca_vars].copy(); R['pca_missing'] = P.isna().sum().to_dict()
P = P.fillna(P.median())                              # median imputation for PCA only
Z = StandardScaler().fit_transform(P)
pca = PCA().fit(Z)
ev = pca.explained_variance_ratio_
load = pd.DataFrame(pca.components_[:3].T, index=pca_vars, columns=['PC1','PC2','PC3']).round(2)
print(load); print(ev.round(3), ev.cumsum().round(3))
R['pca'] = {'ev':ev.round(4).tolist(), 'cum':ev.cumsum().round(4).tolist(), 'load':load.to_dict(), 'eig':pca.explained_variance_.round(2).tolist()}
R['pca_kaiser'] = int((pca.explained_variance_ > 1).sum())
