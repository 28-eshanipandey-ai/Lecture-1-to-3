def rank_band(r):
    """Turn a numeric world rank into a business band."""
    if r <= 50:  return 'Top 50'
    if r <= 100: return '51-100'
    if r <= 200: return '101-200'
    if r <= 400: return '201-400'
    return '401+'

def iqr_fences(s):
    """Return the lower and upper Tukey fences of a numeric Series."""
    q1, q3 = s.quantile(.25), s.quantile(.75)
    return q1 - 1.5*(q3-q1), q3 + 1.5*(q3-q1)

